import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
const read=(path)=>readFile(new URL(path,import.meta.url),"utf8");
const pkg=JSON.parse(await read("../package.json"));
const rr=await read("../react-router.config.ts");
const routes=await read("../app/routes.ts");
const leads=await read("../functions/api/leads.ts");
const health=await read("../functions/api/health.ts");
const manifest=JSON.parse(await read("../public/manifest.webmanifest"));
assert.equal(pkg.scripts?.build,"react-router build");
assert.match(rr,/ssr:\s*false/);
assert.doesNotMatch(rr,/vercel/i);
assert.equal(pkg.dependencies?.["@vercel/react-router"],undefined);
assert.equal(pkg.devDependencies?.["@vercel/react-router"],undefined);
assert.doesNotMatch(routes,/auth\/|webhooks|api\.cron|app\.tsx/);
assert.match(leads,/merchant_leads/);
assert.match(leads,/lead_rate_limits/);
assert.match(leads,/request\.headers\.get\("Origin"\)/);
assert.match(leads,/body\.consent!==true/);
assert.match(leads,/crypto\.subtle\.digest/);
assert.match(health,/NODUS_DB/);
assert.equal(manifest.display,"standalone");
assert.ok(manifest.icons?.length,"PWA icons must be configured");
console.log("NODUS Cloudflare release configuration checks passed.");
